"""Agent tool factories, split by category - see each submodule for the
tools it builds:

- common.py: shared constants/helpers (output parsing/condensation,
  target/session resolution, the one-shot exec primitive).
- file_tools.py: local file read/write/list/download (create_file_tools).
- pentest_tools.py: Tier 1 one-shot tools - nmap/hydra/gobuster/
  searchsploit/metasploit (create_pentest_tools).
- guided_session_tools.py: Tier 2 guided ftp/ssh/telnet tools
  (create_guided_session_tools).
- terminal_tools.py: run/new_session/switch_session/list_sessions/
  close_session/interrupt_session (create_terminal_tools).
- scripting_tools.py: reserved for a future run_python_script tool.
- admin_tools.py: package installs, request_port_access, the raw
  execute_kali_command escape hatch, report_vulnerability/
  log_attack_attempt/finish_task.
- builders.py: build_agent_tools and the per-role build_*_agent_tools
  gatherers.

Every name below is re-exported so `from src.core.agent import
agent_tools; agent_tools.X` and `from src.core.agent.agent_tools import X`
both keep working exactly as they did when this was a single flat module."""

