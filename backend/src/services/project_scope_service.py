import uuid

from src.core.database_manager import db_manager
from src.schemas.project_scheme import AuthorizationAcknowledgment, ProjectScope
from src.schemas.scope_parsing import is_network_in_any, parse_host_range


class ProjectScopeService:
    @staticmethod
    def is_acknowledged(project_id: str | uuid.UUID) -> bool:
        acknowledgment = db_manager.get_latest_acknowledgment(project_id)
        if acknowledgment is None:
            return False

        scope = db_manager.get_project_scope(project_id)

        return ProjectScopeService._is_host_range_contained(
            scope.host_range, acknowledgment.acknowledged_host_range
        ) and ProjectScopeService._is_port_range_contained(
            scope.port_range_start,
            scope.port_range_end,
            acknowledgment.acknowledged_port_range_start,
            acknowledgment.acknowledged_port_range_end,
        )

    @staticmethod
    def _is_host_range_contained(current_host_range: str, acknowledged_host_range: str) -> bool:
        current_networks = parse_host_range(current_host_range)
        acknowledged_networks = parse_host_range(acknowledged_host_range)

        # `current_host_range` may be a comma-separated list - EVERY entry
        # has to fall inside at least one acknowledged entry, not just the
        # first one, or a widened extra entry could ride along unnoticed.
        return all(
            is_network_in_any(current_network, acknowledged_networks)
            for current_network in current_networks
        )

    @staticmethod
    def _is_port_range_contained(
        current_start: int,
        current_end: int,
        acknowledged_start: int,
        acknowledged_end: int,
    ) -> bool:
        return current_start >= acknowledged_start and current_end <= acknowledged_end

    @staticmethod
    def _validate_scope_fields(host_range: str, port_range_start: int, port_range_end: int) -> None:
        # Raises ValueError on anything unparseable - let it propagate,
        # same convention as every other field validation in this repo.
        parse_host_range(host_range)

        if not (1 <= port_range_start <= 65535 and 1 <= port_range_end <= 65535):
            raise ValueError(
                "port_range_start and port_range_end must each be between 1 and 65535"
            )
        if port_range_start > port_range_end:
            raise ValueError("port_range_start must not be greater than port_range_end")

    @staticmethod
    def create_scope(
        project_id: str | uuid.UUID,
        host_range: str,
        port_range_start: int,
        port_range_end: int,
    ) -> ProjectScope:
        ProjectScopeService._validate_scope_fields(host_range, port_range_start, port_range_end)

        scope = ProjectScope(
            project_id=project_id,
            host_range=host_range,
            port_range_start=port_range_start,
            port_range_end=port_range_end,
        )
        # ProjectScope's PK is project_id, not an autogenerated surrogate -
        # db_manager's merge-based update_project_scope inserts when no row
        # with that PK exists yet, so it doubles as the create path too.
        return db_manager.update_project_scope(scope)

    @staticmethod
    def update_scope(
        project_id: str | uuid.UUID,
        host_range: str,
        port_range_start: int,
        port_range_end: int,
    ) -> ProjectScope:
        ProjectScopeService._validate_scope_fields(host_range, port_range_start, port_range_end)

        scope = ProjectScope(
            project_id=project_id,
            host_range=host_range,
            port_range_start=port_range_start,
            port_range_end=port_range_end,
        )
        # Acknowledgment state is never cached on the scope row itself -
        # is_acknowledged always recomputes it live against the latest
        # AuthorizationAcknowledgment, so there's nothing to touch here.
        return db_manager.update_project_scope(scope)

    @staticmethod
    def submit_acknowledgment(
        project_id: str | uuid.UUID, acknowledged_by: str, description: str
    ) -> AuthorizationAcknowledgment:
        scope = db_manager.get_project_scope(project_id)

        acknowledgment = AuthorizationAcknowledgment(
            project_id=project_id,
            acknowledged_by=acknowledged_by,
            description=description,
            acknowledged_host_range=scope.host_range,
            acknowledged_port_range_start=scope.port_range_start,
            acknowledged_port_range_end=scope.port_range_end,
        )
        return db_manager.add_authorization_acknowledgment(acknowledgment)
